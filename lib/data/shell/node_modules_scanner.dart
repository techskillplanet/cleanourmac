import 'dart:io';
import '../../domain/models/node_modules_entry.dart';
import 'shell_runner.dart';

class NodeModulesScanner {
  final ShellRunner _runner;
  NodeModulesScanner(this._runner);

  // Scans the given project roots for node_modules directories.
  Future<List<NodeModulesEntry>> scan(List<String> roots) async {
    final existing = <String>[];
    for (final root in roots) {
      try {
        if (await Directory(
          root,
        ).exists().timeout(const Duration(seconds: 2))) {
          existing.add(root);
        }
      } catch (_) {
        // Ignore missing or unresponsive project roots.
      }
    }
    if (existing.isEmpty) return const [];

    // Locate node_modules dirs (prune so we don't descend into them).
    final findResult = await _runner.run('find', [
      ...existing,
      '-type',
      'd',
      '-name',
      'node_modules',
      '-prune',
      '-print',
    ]);
    if (findResult.exitCode != 0) return const [];
    final paths = findResult.stdout
        .split('\n')
        .map((e) => e.trim())
        .where((e) => e.isNotEmpty)
        .toList();
    if (paths.isEmpty) return const [];

    final sizes = await _sizes(paths);
    final result = <NodeModulesEntry>[];
    for (final path in paths) {
      final size = sizes[path] ?? 0;
      if (size <= 0) continue;
      result.add(
        NodeModulesEntry(
          path: path,
          sizeBytes: size,
          lastModifiedAt: await _mtime(path),
        ),
      );
    }
    result.sort((a, b) => a.lastModifiedAt.compareTo(b.lastModifiedAt));
    return result;
  }

  Future<Map<String, int>> _sizes(List<String> paths) async {
    final result = await _runner.run('du', ['-sk', ...paths]);
    final map = <String, int>{};
    for (final line in result.stdout.trim().split('\n')) {
      final parts = line.trim().split('\t');
      if (parts.length < 2) continue;
      final kb = int.tryParse(parts[0].trim());
      if (kb == null) continue;
      map[parts.sublist(1).join('\t').trim()] = kb * 1024;
    }
    return map;
  }

  Future<DateTime> _mtime(String path) async {
    try {
      final st = await FileStat.stat(path).timeout(const Duration(seconds: 2));
      if (st.modified.millisecondsSinceEpoch != 0) return st.modified;
    } catch (_) {}
    return DateTime.now();
  }
}
