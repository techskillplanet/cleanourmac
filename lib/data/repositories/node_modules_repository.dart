import 'dart:io';
import '../../domain/models/node_modules_entry.dart';
import '../safety/path_guard.dart';
import '../shell/node_modules_scanner.dart';

class NodeModulesRepository {
  final NodeModulesScanner _scanner;
  final PathGuard _guard;
  NodeModulesRepository(this._scanner, this._guard);

  Future<List<NodeModulesEntry>> list(List<String> roots) => _scanner.scan(roots);

  Future<int> delete(List<NodeModulesEntry> entries) async {
    var reclaimed = 0;
    for (final e in entries) {
      try {
        _guard.assertDeletable(e.path);
        await Directory(e.path).delete(recursive: true);
        reclaimed += e.sizeBytes;
      } catch (_) {
        // skip protected/unexpected paths
      }
    }
    return reclaimed;
  }
}
