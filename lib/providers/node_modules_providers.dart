import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../domain/models/node_modules_entry.dart';
import 'infra_providers.dart';

final nodeModulesProvider = FutureProvider<List<NodeModulesEntry>>((ref) {
  final settings = ref.watch(settingsProvider);
  return ref.watch(nodeModulesRepositoryProvider).list(settings.nodeModulesRoots);
});
