import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../domain/models/node_modules_entry.dart';
import 'infra_providers.dart';

final nodeModulesProvider = FutureProvider<List<NodeModulesEntry>>((ref) {
  final settings = ref.watch(settingsProvider);
  return ref
      .watch(nodeModulesRepositoryProvider)
      .list(settings.nodeModulesRoots)
      .then((entries) {
        if (!settings.lruEnabled) return entries;
        final cutoff = DateTime.now().subtract(const Duration(days: 30));
        for (final entry in entries) {
          entry.selected = entry.lastModifiedAt.isBefore(cutoff);
        }
        return entries;
      });
});
