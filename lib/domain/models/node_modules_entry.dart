class NodeModulesEntry {
  final String path;
  final int sizeBytes;
  final DateTime lastModifiedAt;
  bool selected;

  NodeModulesEntry({
    required this.path,
    required this.sizeBytes,
    required this.lastModifiedAt,
    this.selected = false,
  });

  String get projectName {
    final parts = path.split('/');
    // node_modules sits inside the project root; use the project folder name.
    return parts.length >= 2 ? parts[parts.length - 2] : path;
  }

  NodeModulesEntry copyWith({bool? selected}) => NodeModulesEntry(
        path: path,
        sizeBytes: sizeBytes,
        lastModifiedAt: lastModifiedAt,
        selected: selected ?? this.selected,
      );
}
